<?php
declare(strict_types=1);

/**
 * Renders the `DAG = {...}` Python module from a normalized definition.
 * Used by the editor when saving; the file is always re-validated by the
 * loader before it is committed.
 */
final class DagWriter
{
    public static function toPython(array $dag): string
    {
        $lines = [];
        $lines[] = '# generated by the smilir editor — ' . Env::now();
        $lines[] = '';
        $lines[] = 'DAG = {';
        $lines[] = '    "name": ' . self::str((string) $dag['name']) . ',';
        if (($dag['schedule_type'] ?? 'cron') === 'interval') {
            $lines[] = '    "schedule": ' . self::str('interval:' . (int) $dag['schedule']) . ',';
        } else {
            $lines[] = '    "schedule": ' . self::str((string) $dag['schedule']) . ',';
        }
        if (!empty($dag['venv'])) {
            $lines[] = '    "venv": ' . self::str((string) $dag['venv']) . ',';
        } else {
            $lines[] = '    "venv": None,';
        }
        $lines[] = '    "max_concurrency": ' . (int) ($dag['max_concurrency'] ?? 1) . ',';
        $lines[] = '';
        $lines[] = '    "tasks": [';
        foreach ($dag['tasks'] as $i => $t) {
            $rows = [];
            $rows[] = '"name": ' . self::str((string) $t['name']);
            if (!empty($t['func'])) {
                $rows[] = '"func": ' . self::str((string) $t['func']);
            } elseif (!empty($t['command'])) {
                $rows[] = '"command": ' . self::str((string) $t['command']);
            }
            if (!empty($t['depends_on']) && is_array($t['depends_on'])) {
                $rows[] = '"depends_on": [' . implode(', ', array_map(
                    static fn (string $d): string => DagWriter::str($d),
                    $t['depends_on']
                )) . ']';
            }
            if (!empty($t['retries'])) {
                $rows[] = '"retries": ' . (int) $t['retries'];
            }
            if (!empty($t['retry_delay']) && (int) $t['retry_delay'] !== 300) {
                $rows[] = '"retry_delay": ' . (int) $t['retry_delay'];
            }
            if (!empty($t['timeout'])) {
                $rows[] = '"timeout": ' . (int) $t['timeout'];
            }
            if (!empty($t['email_on_failure'])) {
                $rows[] = '"email_on_failure": True';
            }
            $lines[] = '        {';
            foreach ($rows as $r) {
                $lines[] = '            ' . $r . ',';
            }
            $lines[] = '        },';
        }
        $lines[] = '    ],';
        $lines[] = '}';
        $lines[] = '';
        return implode("\n", $lines);
    }

    private static function str(string $value): string
    {
        return "'" . str_replace(["\\", "'"], ["\\\\", "\\'"], $value) . "'";
    }
}
